import React, { useState } from 'react';
import {
  BookOpen,
  Download,
  CheckCircle,
  FileText,
  Terminal,
  Layers,
  ArrowRight,
  Sparkles,
  Copy,
  Check,
} from 'lucide-react';
import { RepositoryProject, UserProfile } from '../types';
import { sound } from '../utils/sound';

interface OnboardingGuideViewProps {
  project?: RepositoryProject;
  user: UserProfile;
}

export const OnboardingGuideView: React.FC<OnboardingGuideViewProps> = ({ project, user }) => {
  const [copied, setCopied] = useState(false);

  const guide = project?.onboardingGuide || {
    overview: `${project?.name || 'Codebase'} follows a modern modular architecture designed for high maintainability, clear separation of concerns, and rapid onboarding.`,
    techStack: ['TypeScript', 'React 19', 'Express', 'Tailwind CSS', 'Vite'],
    entryPoint: project?.files[0]?.path || 'src/main.tsx',
    criticalFiles: project?.files.slice(0, 4).map((f) => f.path) || [
      'src/main.tsx',
      'src/App.tsx',
      'server.ts',
      'package.json',
    ],
    learningPath: [
      {
        step: 'Day 1: Sanctuary Setup & Architecture Orientation',
        description:
          'Set up your local environment, install dependencies, and trace the application entry point to understand how providers are initialized.',
        files: ['package.json', project?.files[0]?.path || 'src/main.tsx'],
      },
      {
        step: 'Day 2: State Flow & API Communication',
        description:
          'Understand how state stores communicate with backend REST endpoints and how error boundaries catch unhandled exceptions.',
        files: project?.files.slice(1, 3).map((f) => f.path) || ['src/services/api.ts'],
      },
      {
        step: 'Day 3: Your First Safe Pull Request',
        description:
          'Run the CodeBloom side-by-side debugger on test files, verify 0 cyclical dependencies, and submit your first verified PR.',
        files: project?.files.slice(0, 2).map((f) => f.path) || ['src/App.tsx'],
      },
    ],
  };

  const generateMarkdown = () => {
    return `# Onboarding Guide: ${project?.name || 'Codebase'}
Generated by CodeBloom for **${user.fullName}** (${user.skillLevel} Developer)

## 1. Project Overview
${guide.overview}

## 2. Technology Stack
${guide.techStack.map((t) => `- ${t}`).join('\n')}

## 3. Application Entry Point
\`${guide.entryPoint}\`

## 4. Critical Files to Read First
${guide.criticalFiles.map((f) => `- \`${f}\``).join('\n')}

## 5. Recommended Learning Sequence
${guide.learningPath
  .map(
    (item, idx) => `### ${idx + 1}. ${item.step}
${item.description}
*Recommended Files:* ${item.files.join(', ')}`
  )
  .join('\n\n')}

---
*Generated by CodeBloom AI Companion · All rights reserved.*
`;
  };

  const handleDownloadMarkdown = () => {
    sound.playBloomChime(783.99);
    const md = generateMarkdown();
    const blob = new Blob([md], { type: 'text/markdown' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `${project?.name || 'codebase'}_onboarding_guide.md`;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
  };

  const handleCopyMarkdown = () => {
    sound.playSoftTick();
    navigator.clipboard.writeText(generateMarkdown());
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  return (
    <div className="p-6 sm:p-8 space-y-6 max-w-5xl mx-auto">
      
      {/* Header */}
      <div className="bg-white rounded-3xl border-2 border-[#493B55] pixel-box-shadow p-6 flex flex-col md:flex-row md:items-center justify-between gap-4">
        <div>
          <div className="flex items-center gap-2 text-xs font-semibold text-[#493B55]/70 mb-1">
            <span className="font-pixel">PERSONALIZED LEARNING GUIDE</span>
            <span aria-hidden="true">·</span>
            <span>Tailored for {user.skillLevel}</span>
          </div>
          <h2 className="font-pixel text-xl sm:text-2xl text-[#493B55]">
            ONBOARDING GUIDE: {project?.name || 'REPOSITORY'}
          </h2>
        </div>

        <div className="flex items-center gap-2">
          <button
            onClick={handleCopyMarkdown}
            className="p-2 bg-[#FFF9F2] hover:bg-white border border-[#493B55]/25 rounded-xl text-xs font-semibold text-[#493B55] flex items-center gap-1.5 cursor-pointer"
          >
            {copied ? <Check className="w-3.5 h-3.5 text-emerald-600" /> : <Copy className="w-3.5 h-3.5" />}
            <span>{copied ? 'Copied' : 'Copy MD'}</span>
          </button>

          <button
            onClick={handleDownloadMarkdown}
            className="bg-[#FFF9F2] hover:bg-white text-[#493B55] border border-[#493B55]/25 px-3 py-2 rounded-xl text-xs font-bold flex items-center gap-1.5 transition-colors cursor-pointer"
          >
            <Download className="w-3.5 h-3.5" />
            <span>Export MD</span>
          </button>

          <button
            onClick={() => {
              sound.playBloomChime(783.99);
              window.print();
            }}
            className="bg-[#493B55] text-white px-3.5 py-2 rounded-xl text-xs font-bold flex items-center gap-1.5 transition-colors cursor-pointer hover:bg-[#3A2D44]"
          >
            <FileText className="w-3.5 h-3.5" />
            <span>Export PDF / Print</span>
          </button>
        </div>
      </div>

      {/* Guide Content */}
      <div className="bg-white rounded-3xl border-2 border-[#493B55] pixel-box-shadow p-6 sm:p-8 space-y-8">
        
        {/* Section 1: Overview */}
        <div>
          <div className="flex items-center gap-2 text-xs font-bold uppercase tracking-wider text-[#493B55]/60 mb-2">
            <span>01. Project Architecture Overview</span>
          </div>
          <p className="text-sm text-[#493B55]/90 leading-relaxed font-sans bg-[#FFF9F2] p-4 rounded-2xl border border-[#493B55]/10">
            {guide.overview}
          </p>
        </div>

        {/* Section 2: Tech Stack */}
        <div>
          <div className="flex items-center gap-2 text-xs font-bold uppercase tracking-wider text-[#493B55]/60 mb-3">
            <span>02. Detected Technology Stack</span>
          </div>
          <div className="flex flex-wrap gap-2">
            {guide.techStack.map((tech, idx) => (
              <span
                key={idx}
                className="px-3 py-1 rounded-xl bg-[#DCCFF5] text-[#493B55] font-code text-xs font-bold border border-[#493B55]/20"
              >
                {tech}
              </span>
            ))}
          </div>
        </div>

        {/* Section 3: Entry Point & Critical Files */}
        <div className="grid grid-cols-1 md:grid-cols-2 gap-6">
          <div className="p-4 rounded-2xl bg-[#FFF9F2] border border-[#493B55]/15">
            <div className="text-xs font-bold text-[#493B55] mb-2 flex items-center gap-1.5">
              <Terminal className="w-4 h-4 text-[#493B55]" />
              <span>Application Entry Point</span>
            </div>
            <div className="font-code text-xs font-bold text-[#493B55] bg-white p-2.5 rounded-xl border border-[#493B55]/20">
              {guide.entryPoint}
            </div>
            <p className="text-[11px] text-[#493B55]/70 mt-2 font-sans">
              Start here to trace how the application initializes context and handles global providers.
            </p>
          </div>

          <div className="p-4 rounded-2xl bg-[#FFF9F2] border border-[#493B55]/15">
            <div className="text-xs font-bold text-[#493B55] mb-2 flex items-center gap-1.5">
              <FileText className="w-4 h-4 text-[#493B55]" />
              <span>High Priority Files</span>
            </div>
            <div className="space-y-1.5">
              {guide.criticalFiles.map((f, i) => (
                <div
                  key={i}
                  className="font-code text-xs text-[#493B55] bg-white px-2.5 py-1 rounded-lg border border-[#493B55]/15 truncate"
                >
                  {f}
                </div>
              ))}
            </div>
          </div>
        </div>

        {/* Section 4: 3-Day Personalized Learning Path */}
        <div>
          <div className="flex items-center gap-2 text-xs font-bold uppercase tracking-wider text-[#493B55]/60 mb-4">
            <span>03. Recommended Onboarding Roadmap</span>
          </div>

          <div className="space-y-4">
            {guide.learningPath.map((item, idx) => (
              <div
                key={idx}
                className="p-5 rounded-2xl bg-[#FFF9F2] border-2 border-[#493B55]/15 hover:border-[#493B55]/40 transition-colors"
              >
                <div className="flex items-center justify-between mb-2">
                  <h4 className="font-bold text-sm text-[#493B55] flex items-center gap-2">
                    <span className="font-pixel text-xs bg-[#F8DCE8] px-2 py-0.5 rounded border border-[#493B55]/20">
                      Phase {idx + 1}
                    </span>
                    <span>{item.step}</span>
                  </h4>
                </div>

                <p className="text-xs text-[#493B55]/85 leading-relaxed font-sans mb-3">
                  {item.description}
                </p>

                <div className="flex flex-wrap items-center gap-1.5 text-[11px]">
                  <span className="text-[#493B55]/60 font-semibold">Focus files:</span>
                  {item.files.map((file, fIdx) => (
                    <span
                      key={fIdx}
                      className="px-2 py-0.5 rounded bg-white border border-[#493B55]/20 font-code text-[#493B55]"
                    >
                      {file}
                    </span>
                  ))}
                </div>
              </div>
            ))}
          </div>
        </div>

      </div>

    </div>
  );
};
